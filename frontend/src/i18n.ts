export type Key = keyof Dict
const dicts: Record<string, Dict> = { fr, en }

let lang = (() => {
  try {
    const saved = localStorage.getItem('lm.lang')
    if (saved && dicts[saved]) return saved
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith('fr') ? 'fr' : 'en'
})()

const listeners = new Set<() => void>()

export function setLanguage(l: string) {
  if (!dicts[l] || l === lang) return
  lang = l
  try {
    localStorage.setItem('lm.lang', l)
  } catch {
    /* ignore */
  }
  document.documentElement.lang = l
  listeners.forEach((f) => f())
}

export function getLanguage() {
  return lang
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? fr[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v))
  return s
}

export function hasKey(key: string): key is Key {
  return key in fr
}

/** Re-render on language change. */
export function useLanguage() {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb)
      return () => listeners.delete(cb)
    },
    () => lang,
  )
}
